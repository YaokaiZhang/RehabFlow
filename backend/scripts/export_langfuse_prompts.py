"""Export the graph's default prompts for Langfuse prompt management.

Writes one ``backend/prompts/langfuse/<prompt-name>.txt`` file per prompt, plus
an index README, from ``app/ai/prompt_defaults.py``. Paste each file into
Langfuse as a *text* prompt with the same name, or upload them all:

    python scripts/export_langfuse_prompts.py                    # write files only
    python scripts/export_langfuse_prompts.py --upload           # also create versions labelled "staging"
    python scripts/export_langfuse_prompts.py --upload --label production

The script is standalone: writing files needs only Python, and uploading needs
only the ``langfuse`` package (``pip install langfuse``), not the backend's
other dependencies. Uploading reads LANGFUSE_PUBLIC_KEY, LANGFUSE_SECRET_KEY and
LANGFUSE_BASE_URL (or LANGFUSE_HOST) from the environment. Each upload creates a
new prompt version; unchanged text still makes a new version, so upload only
when you mean to.
"""
from __future__ import annotations

import argparse
import importlib.util
import os
import re
import sys
from pathlib import Path

BACKEND_DIR = Path(__file__).resolve().parents[1]
EXPORT_DIR = BACKEND_DIR / "prompts" / "langfuse"
_VARIABLE = re.compile(r"\{\{\s*([A-Za-z_][A-Za-z0-9_]*)\s*\}\}")


def _load_default_prompts():
    # Load the module by path: importing ``app.ai`` would pull in the whole graph
    # and every backend dependency.
    path = BACKEND_DIR / "app" / "ai" / "prompt_defaults.py"
    spec = importlib.util.spec_from_file_location("_rehab_prompt_defaults", path)
    module = importlib.util.module_from_spec(spec)
    sys.modules[spec.name] = module
    spec.loader.exec_module(module)
    return module.DEFAULT_PROMPTS


DEFAULT_PROMPTS = _load_default_prompts()


def template_variables(text: str) -> set[str]:
    return set(_VARIABLE.findall(text))


def _readme() -> str:
    lines = [
        "# Langfuse prompts",
        "",
        "Generated by `backend/scripts/export_langfuse_prompts.py` from",
        "`backend/app/ai/prompt_defaults.py`. Do not edit these files by hand.",
        "",
        "Create each one in Langfuse as a **text** prompt whose name is the file name",
        "without `.txt`, then give the version you want the app to use the label set in",
        "`LANGFUSE_PROMPT_LABEL` (default `production`). A Langfuse version must keep",
        "exactly the listed `{{variables}}`, or the app ignores it and uses the default.",
        "",
        "| Prompt name | Variables | Used for |",
        "| --- | --- | --- |",
    ]
    for name, default in DEFAULT_PROMPTS.items():
        variables = ", ".join(f"`{{{{{v}}}}}`" for v in sorted(template_variables(default.text))) or "none"
        lines.append(f"| `{name}` | {variables} | {default.description} |")
    lines.append("")
    return "\n".join(lines)


def write_files(directory: Path = EXPORT_DIR) -> list[Path]:
    directory.mkdir(parents=True, exist_ok=True)
    expected = {f"{name}.txt" for name in DEFAULT_PROMPTS}
    for stale in directory.glob("*.txt"):
        if stale.name not in expected:
            stale.unlink()
    written = []
    for name, default in DEFAULT_PROMPTS.items():
        path = directory / f"{name}.txt"
        path.write_text(default.text, encoding="utf-8")
        written.append(path)
    (directory / "README.md").write_text(_readme(), encoding="utf-8")
    return written


def upload(label: str) -> None:
    public_key = os.getenv("LANGFUSE_PUBLIC_KEY", "").strip()
    secret_key = os.getenv("LANGFUSE_SECRET_KEY", "").strip()
    base_url = (os.getenv("LANGFUSE_BASE_URL") or os.getenv("LANGFUSE_HOST") or "http://localhost:3100").strip()
    if not public_key or not secret_key:
        raise SystemExit("Set LANGFUSE_PUBLIC_KEY and LANGFUSE_SECRET_KEY (and LANGFUSE_BASE_URL).")
    try:
        from langfuse import Langfuse
    except ImportError:
        raise SystemExit("Uploading needs the langfuse package: pip install langfuse")

    client = Langfuse(public_key=public_key, secret_key=secret_key, base_url=base_url)
    rejected = (
        f"Langfuse at {base_url} rejected the keys ({public_key}). Copy a key pair from that "
        "Langfuse's UI (project Settings > API Keys) into LANGFUSE_PUBLIC_KEY and LANGFUSE_SECRET_KEY."
    )
    try:
        authorized = client.auth_check()
    except Exception as exc:
        if getattr(exc, "status_code", None) in (401, 403):
            raise SystemExit(rejected)
        raise SystemExit(f"Cannot reach Langfuse at {base_url}: {type(exc).__name__}: {exc}")
    if not authorized:
        raise SystemExit(rejected)
    for name, default in DEFAULT_PROMPTS.items():
        created = client.create_prompt(
            name=name,
            prompt=default.text,
            type="text",
            labels=[label],
            tags=["rehabflow"],
            commit_message="Imported from app/ai/prompt_defaults.py",
        )
        print(f"uploaded {name} version {getattr(created, 'version', '?')} label {label}")
    client.flush()


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("--upload", action="store_true", help="create a Langfuse version of every prompt")
    parser.add_argument("--label", default="staging", help="label for uploaded versions (default: staging)")
    args = parser.parse_args()
    for path in write_files():
        print(f"wrote {path.relative_to(Path.cwd()) if path.is_relative_to(Path.cwd()) else path}")
    if args.upload:
        upload(args.label)


if __name__ == "__main__":
    main()
